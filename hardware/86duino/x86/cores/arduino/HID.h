//	Low level key report: up to 6 keys and shift, ctrl etc at once
typedef struct
{
	unsigned char modifiers;
	unsigned char reserved;
	unsigned char keys[6];
} KeyReport;

class Keyboard_
{
private:
	KeyReport _keyReport;
	void sendReport(KeyReport* keys);
public:
	Keyboard_(void);
	void begin(void);
	void end(void);
	virtual size_t write(unsigned char k);
	virtual size_t press(unsigned char k);
	virtual size_t release(unsigned char k);
	virtual void releaseAll(void);
};

void HID_SendReport(unsigned char id, const void* data, int len)
{
	int i, j = 0;
	unsigned char senddata[len+1];
	unsigned char* tmp = (unsigned char*)data;
	if(hid == NULL) return;
	
	len += 1;
	senddata[0] = id;
	for(i=1; i<len; i++, j++) senddata[i] = tmp[j];

    if (USBHID_WFIFOFree(hid) > 0) {
        
        USBHID_WriteInputReport(hid, senddata, len);
        
    }
}

Mouse_::Mouse_(void) : _buttons(0)
{
}

void Mouse_::begin(void) 
{
}

void Mouse_::end(void) 
{
}

void Mouse_::click(unsigned char b)
{
	_buttons = b;
	move(0,0,0);
	_buttons = 0;
	move(0,0,0);
}

void Mouse_::move(signed char x, signed char y, signed char wheel)
{
	unsigned char m[4];
	m[0] = _buttons;
	m[1] = x;
	m[2] = y;
	m[3] = wheel;
	HID_SendReport(1, m, 4);
}

void Mouse_::buttons(unsigned char b)
{
	if (b != _buttons)
	{
		_buttons = b;
		move(0,0,0);
	}
}

void Mouse_::press(unsigned char b) 
{
	buttons(_buttons | b);
}

void Mouse_::release(unsigned char b)
{
	buttons(_buttons & ~b);
}

bool Mouse_::isPressed(unsigned char b)
{
	if ((b & _buttons) > 0) 
		return true;
	return false;
}

